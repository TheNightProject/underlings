test('a GitLab hiccup leaves items waiting rather than handing them back', async () => {
  const fake = fakeWorld();
  const pass = await launchOne(fake);
  fake.world.threads = [thread('t1', [note(ME, 'MAJOR: off by one', '2026-11-01T00:00:00Z')])];
  agentQueues(pass, [finding(), reply('t1', 'not-fixed', 'Still off by one.')]);
  const { freshMr, discussions } = fake.ports;
  fake.ports.freshMr = async () => {
    throw new Error('502');
  };
  await afterHold(fake);
  fake.ports.freshMr = freshMr;
  fake.ports.discussions = async () => {
    throw new Error('502');
  };
  await autoTick(context(fake.world), fake.ports);
  assert.equal(fake.calls.posted.length, 1, 'the finding needed no thread read');
  assert.ok(!loadQueue().some((c) => c.auto?.held), 'nothing was handed back over a blip');
  fake.ports.discussions = discussions;
  await autoTick(context(fake.world), fake.ports);
  assert.equal(fake.calls.posted.length, 2, 'and the reply goes once GitLab answers');
});

