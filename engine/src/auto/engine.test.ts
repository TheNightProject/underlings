const GATES: [string, (fake: Fake) => void, RegExp][] = [
  ['a red pipeline', (f) => (f.world.mrs = [mr({ pipeline: 'FAILED' })]), /pipeline is failed/],
  ['an open thread of yours', (f) => (f.world.threads = [thread('t1', [note(ME, 'MINOR: hm', '2026-11-01T00:00:00Z')])]), /threads are unresolved/],
  ['a big diff', (f) => (f.world.diff = { paths: ['src/a.ts'], changedLines: 601, complete: true }), /601 changed lines/],
  ['a diff GitLab cut short', (f) => (f.world.diff = { paths: ['src/a.ts'], changedLines: 3, complete: false }), /whole diff/],
  ['a migration', (f) => (f.world.diff = { paths: ['db/migrations/0042_add.sql'], changedLines: 3, complete: true }), /touches db\/migrations/],
  ['the CI file', (f) => (f.world.diff = { paths: ['.gitlab-ci.yml'], changedLines: 3, complete: true }), /touches \.gitlab-ci\.yml/],
  ['a hold you placed by hand', (f) => (f.world.mrs = [mr({ mergeStatus: 'REQUESTED_CHANGES' })]), /by hand/],
];

for (const [name, breakIt, why] of GATES) {
  test(`${name} keeps the approval for you instead of sending it`, async () => {
    const fake = fakeWorld();
    await finishedPass(fake);
    breakIt(fake);
    await afterHold(fake);
    assert.deepEqual(verdictsPosted(fake), []);
    const verdict = loadQueue().find((c) => c.kind === 'verdict');
    assert.equal(verdict?.status, 'pending');
    assert.match(verdict?.auto?.held ?? '', why);
  });
}

