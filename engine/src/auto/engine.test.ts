async function finishedPass(fake: Fake, people = 'heidi:verdict', items: Record<string, unknown>[] = []): Promise<string> {
  const pass = await launchOne(fake, people);
  agentQueues(pass, items);
  markPassDone(pass);
  await autoPoll(context(fake.world, people), fake.ports);
  return pass;
}

function verdictsPosted(fake: Fake): string[] {
  return fake.calls.posted.filter((p) => p.item.kind === 'verdict').map((p) => p.item.verdict ?? '');
}

test('approves when every gate holds, after the hold', async () => {
  const fake = fakeWorld();
  await finishedPass(fake);
  assert.deepEqual(verdictsPosted(fake), [], 'not before the window');
  await afterHold(fake);
  assert.deepEqual(verdictsPosted(fake), ['approve']);
});

