const KEY = 'acme/engine!621';

function passId(): string {
  const id = loadAutoMemory()[KEY]?.pass?.id;
  assert.ok(id, 'a pass should have been launched');
  return id;
}

function agentQueues(pass: string, items: Record<string, unknown>[]): void {
  const base = { projectPath: 'acme/engine', projectId: 1001, iid: 621, createdBy: `auto:${pass}` };
  addToQueue(items.map((item, n) => queueInput({ ...base, ...item }, n)));
}

function finding(severity = 'MINOR', body = 'this breaks on an empty list'): Record<string, unknown> {
  return { severity, body };
}

function reply(replyTo: string, outcome: string, body = 'Fixed, thanks.'): Record<string, unknown> {
  return { kind: 'reply', replyTo, outcome, body };
}

type Fake = ReturnType<typeof fakeWorld>;

async function launchOne(fake: Fake, people = 'heidi:verdict'): Promise<string> {
  await autoPoll(context(fake.world, people), fake.ports);
  return passId();
}

/** Seen by a tick first, as the TUI would within seconds, then past the two minute hold. */
async function afterHold(fake: Fake, people = 'heidi:verdict'): Promise<void> {
  await autoTick(context(fake.world, people), fake.ports);
  fake.world.clock += 3 * MINUTE;
  await autoTick(context(fake.world, people), fake.ports);
}


